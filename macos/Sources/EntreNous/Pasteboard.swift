import AppKit
import UniformTypeIdentifiers

/// Watches the general pasteboard and writes received content to it.
///  - content marked concealed / transient (password managers) is never shared;
///  - what we write is marked concealed, so clipboard history tools ignore it;
final class PasteboardWatcher {
    var onCopy: (([String: Any]) -> Void)?
    var fileToken: ((URL) -> String)?
    /// Paused: copies are not even read, and those made meanwhile are never sent.
    var paused = false

    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var ownChange = -1
    private var timer: Timer?

    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let maxImage = 32 * 1024 * 1024

    init() {
        lastChange = pb.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.1
    }

    private func poll() {
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        guard count != ownChange else { return } // what we wrote ourselves
        guard !paused else { return }
        let types = Set(pb.types ?? [])
        if types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.autoGenerated) { return }

        // a copy shares one thing: the first file
        if let first = Self.contents(of: pb, token: { [weak self] in self?.fileToken?($0) ?? "" }).first {
            onCopy?(first)
        }
    }

    /// What a pasteboard holds, for the web UI: every file (folders skipped), otherwise an
    /// image, otherwise text. Also used for a drop on the menu bar icon.
    static func contents(of pb: NSPasteboard, token: (URL) -> String) -> [[String: Any]] {
        let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        let files: [[String: Any]] = urls.compactMap { url in
            guard let values = try? url.resourceValues(forKeys: [.fileSizeKey, .isDirectoryKey]),
                  values.isDirectory != true, let size = values.fileSize else { return nil }
            let mime = UTType(filenameExtension: url.pathExtension)?.preferredMIMEType ?? "application/octet-stream"
            return ["kind": "file", "token": token(url), "name": url.lastPathComponent, "size": size, "mime": mime]
        }
        if !files.isEmpty { return files }
        if let png = pngData(pb), png.count <= maxImage {
            return [["kind": "image", "data": png.base64URLEncoded(), "mime": "image/png", "name": "image.png"]]
        }
        if let text = pb.string(forType: .string), !text.isEmpty {
            return [["kind": "text", "text": text]]
        }
        return []
    }

    private static func pngData(_ pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: writing

    func write(text: String) {
        commit {
            pb.declareTypes([.string, Self.concealed], owner: nil)
            pb.setString(text, forType: .string)
        }
    }

    func write(image: Data, mime: String) {
        let type: NSPasteboard.PasteboardType = mime == "image/png" ? .png : .tiff
        let data = type == .png ? image : (NSImage(data: image)?.tiffRepresentation ?? image)
        commit {
            pb.declareTypes([type, Self.concealed], owner: nil)
            pb.setData(data, forType: type)
        }
    }

    func write(file: URL) {
        commit {
            pb.clearContents()
            pb.writeObjects([file as NSURL])
            pb.addTypes([Self.concealed], owner: nil)
        }
    }

    private func commit(_ body: () -> Void) {
        body()
        pb.setData(Data(), forType: Self.concealed)
        ownChange = pb.changeCount
        lastChange = ownChange
    }
}
